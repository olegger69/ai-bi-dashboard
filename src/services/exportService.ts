import { DashboardState, DataRow } from '../core/types';

// --- Экспорт в Markdown ---
export function exportToMarkdown(state: DashboardState): string {
    const { profile, kpis, insights } = state;
    const reportDate = new Date().toLocaleDateString('ru-RU');

    let md = `# AI Business Intelligence Report\n\n`;
    md += `**Дата:** ${reportDate}\n\n`;

    md += `## Dataset Summary\n\n`;
    md += `- Всего записей: ${profile.totalRows}\n`;
    md += `- Всего столбцов: ${profile.totalColumns}\n`;
    md += `- Уникальных значений: ${profile.columns.reduce((sum, col) => sum + col.uniqueCount, 0)}\n`;
    md += `- Пропущенных значений: ${profile.columns.reduce((sum, col) => sum + col.missingCount, 0)}\n\n`;

    if (kpis.length > 0) {
        md += `## Key Performance Indicators\n\n`;
        kpis.forEach(kpi => {
            md += `- **${kpi.label}:** ${kpi.value}`;
            if (kpi.description) md += ` — ${kpi.description}`;
            md += `\n`;
        });
        md += `\n`;
    }

    if (insights) {
        md += `## Executive Summary\n\n${insights.summary}\n\n`;
        if (insights.trends.length > 0) {
            md += `## Trends\n\n`;
            insights.trends.forEach(trend => { md += `- ${trend}\n`; });
            md += `\n`;
        }
        if (insights.anomalies.length > 0) {
            md += `## Anomalies\n\n`;
            insights.anomalies.forEach(anomaly => { md += `- ${anomaly}\n`; });
            md += `\n`;
        }
        if (insights.recommendations.length > 0) {
            md += `## Recommendations\n\n`;
            insights.recommendations.forEach(rec => { md += `- ${rec}\n`; });
            md += `\n`;
        }
        md += `---\n*Generated by ${insights.mode === 'groq' || insights.mode === 'openrouter' ? 'AI' : 'Rules Engine'} on ${insights.generatedAt}*\n`;
    }

    return md;
}

export function downloadMarkdown(content: string, filename: string = 'report.md'): void {
    const blob = new Blob([content], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
}

// --- НОВЫЙ ЭКСПОРТ В CSV ---
export function exportToCSV(data: DataRow[], filename: string = 'filtered_data.csv'): void {
    if (!data || data.length === 0) {
        alert('Нет данных для экспорта');
        return;
    }

    const headers = Object.keys(data[0]);
    const csvRows: string[] = [];

    // Заголовки
    csvRows.push(headers.map(h => `"${h}"`).join(','));

    // Данные
    for (const row of data) {
        const values = headers.map(header => {
            const val = row[header] === null || row[header] === undefined ? '' : String(row[header]);
            return `"${val.replace(/"/g, '""')}"`;
        });
        csvRows.push(values.join(','));
    }

    // Добавляем BOM (\uFEFF) для корректного открытия кириллицы в Excel
    const blob = new Blob(['\uFEFF' + csvRows.join('\n')], { type: 'text/csv;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
}